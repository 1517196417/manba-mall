USE `abcmall`;

-- ----------------------------
-- 站点地图 / 功能导航表
-- ----------------------------
DROP TABLE IF EXISTS `sitemap`;
CREATE TABLE `sitemap` (
  `id`          BIGINT       NOT NULL AUTO_INCREMENT,
  `name`        VARCHAR(100) NOT NULL COMMENT '功能名称',
  `description` VARCHAR(500) DEFAULT NULL COMMENT '功能描述',
  `url`         VARCHAR(500) NOT NULL COMMENT '页面链接',
  `keywords`    VARCHAR(500) DEFAULT NULL COMMENT '关键词，逗号分隔',
  `category`    VARCHAR(50)  DEFAULT NULL COMMENT '功能分类',
  `sort_order`  INT          DEFAULT 0 COMMENT '排序',
  `status`      TINYINT      DEFAULT 1 COMMENT '0禁用 1启用',
  `create_time` DATETIME     DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='站点地图/功能导航表';

-- ----------------------------
-- 聊天历史表
-- ----------------------------
DROP TABLE IF EXISTS `chat_history`;
CREATE TABLE `chat_history` (
  `id`          BIGINT   NOT NULL AUTO_INCREMENT,
  `session_id`  VARCHAR(64) NOT NULL COMMENT '会话ID',
  `user_id`     BIGINT   DEFAULT NULL COMMENT '用户ID',
  `role`        VARCHAR(20) NOT NULL COMMENT 'user / assistant',
  `content`     TEXT     NOT NULL COMMENT '消息内容',
  `intent`      VARCHAR(50) DEFAULT NULL COMMENT '识别的意图',
  `metadata`    TEXT     DEFAULT NULL COMMENT '附加信息JSON(商品/订单/链接等结构化数据)',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_session` (`session_id`),
  KEY `idx_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI客服聊天历史表';

